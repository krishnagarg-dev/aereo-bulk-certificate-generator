from pathlib import Path
from uuid import uuid4

from reportlab.lib.pagesizes import landscape, A4
from reportlab.pdfgen import canvas


def generate_certificate(*, recipient_name: str, certificate_title: str, event_name: str, output_dir: str) -> str:
    """Generate one certificate and return its filesystem path."""
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    filename = f"{uuid4()}.pdf"
    path = output / filename

    pdf = canvas.Canvas(str(path), pagesize=landscape(A4))
    width, height = landscape(A4)

    pdf.setTitle(certificate_title)
    pdf.setStrokeColorRGB(0.15, 0.15, 0.15)
    pdf.setLineWidth(2)
    pdf.rect(30, 30, width - 60, height - 60)

    pdf.setFont("Helvetica-Bold", 30)
    pdf.drawCentredString(width / 2, height - 120, certificate_title)

    pdf.setFont("Helvetica", 16)
    pdf.drawCentredString(width / 2, height - 165, "This certificate is proudly presented to")

    pdf.setFont("Helvetica-Bold", 28)
    pdf.drawCentredString(width / 2, height - 220, recipient_name)

    pdf.setFont("Helvetica", 15)
    pdf.drawCentredString(width / 2, height - 265, f"for participation in {event_name}")

    pdf.setFont("Helvetica", 10)
    pdf.drawCentredString(width / 2, 65, "Generated by AEREO Bulk Certificate Generator")
    pdf.save()

    return str(path)
